#!/usr/bin/env node
//
// sync-shared-content.js — build-time transclusion for the guide site.
//
// Problem this solves: the guides are meant to be self-contained, but some
// content genuinely belongs in more than one guide (licensing prerequisites,
// credential requests, shared verification steps). Writing it once and linking
// out breaks self-containment. Writing it N times means N copies that drift.
//
// This script lets you author the content once, in docs/shared/snippets/, and
// have it physically expanded into every guide that uses it. The expanded copy
// is committed, so the published HTML is genuinely self-contained: search
// indexing, printing, offline reading, and "view source" all see real content,
// not a fetch placeholder.
//
// Usage:
//   node docs/shared/scripts/sync-shared-content.js            write changes
//   node docs/shared/scripts/sync-shared-content.js --check    exit 1 if stale
//   node docs/shared/scripts/sync-shared-content.js --list     snippet inventory
//   node docs/shared/scripts/sync-shared-content.js --verbose  per-file detail
//
// Restrict to specific files by passing paths after the flags. The pre-commit
// hook does this so it only checks what is staged.
//
// Marker syntax, in any .html or .md file under docs/:
//
//   <!-- shared:begin id="aigw-licensing" vars='{"returnLabel":"step 1"}' -->
//   ...generated, do not hand-edit...
//   <!-- shared:end -->
//
// A begin marker may wrap across lines, so a long vars object stays readable:
//
//   <!-- shared:begin id="aigw-licensing-activation"
//        vars='{
//          "imgBase": "aigw-screenshots",
//          "stepSizing": "Step 1.2"
//        }' -->
//   <!-- shared:end -->
//
// The `vars` attribute is optional. When present it must be single-quoted JSON.
// Inside a snippet, {{name}} is replaced by the matching var. A {{name}} with
// no matching var is an error, so a missing value can never reach the site as
// literal braces. To write a literal "{{" in a snippet, use "&#123;&#123;".

'use strict';

const fs = require('fs');
const path = require('path');

const DOCS_ROOT = path.resolve(__dirname, '..', '..');
const REPO_ROOT = path.resolve(DOCS_ROOT, '..');
const SNIPPET_DIR = path.join(DOCS_ROOT, 'shared', 'snippets');
const SKIP_DIRS = new Set(['shared', 'templates', 'node_modules', '.git']);

// A begin marker may wrap across lines so a long vars object stays readable.
// BEGIN_OPEN_RE matches its first line; everything up to the closing --> is
// then joined and parsed as the attribute text.
const BEGIN_OPEN_RE = /^((?:[ \t]*>)*[ \t]*)<!--\s*shared:begin\b/;
const END_RE = /^(?:[ \t]*>)*[ \t]*<!--\s*shared:end\s*-->[ \t]*$/;
const VAR_RE = /\{\{\s*([A-Za-z_][A-Za-z0-9_]*)\s*\}\}/g;

const GENERATED_NOTICE =
  'Generated by sync-shared-content.js from docs/shared/snippets/%s. ' +
  'Do not edit between the markers; edit the snippet and re-run the script.';

// ── snippet loading ────────────────────────────────────────────────────────

function loadSnippets() {
  const snippets = new Map(); // id -> { html?, md?, meta }
  if (!fs.existsSync(SNIPPET_DIR)) return snippets;

  for (const entry of fs.readdirSync(SNIPPET_DIR, { withFileTypes: true })) {
    if (!entry.isFile()) continue;
    const ext = path.extname(entry.name);
    if (ext !== '.html' && ext !== '.md') continue;

    const id = path.basename(entry.name, ext);
    const raw = fs.readFileSync(path.join(SNIPPET_DIR, entry.name), 'utf8');
    const { meta, body } = splitMeta(raw);

    if (!snippets.has(id)) snippets.set(id, { id, meta: {} });
    const rec = snippets.get(id);
    rec[ext.slice(1)] = body;
    rec.meta = Object.assign({}, meta, rec.meta);
  }
  return snippets;
}

// An optional leading comment block carries author metadata. It is stripped
// from the output so it never reaches the published page.
//
//   <!-- @snippet
//     title: Licensing and activation
//     desc:  What must be true before any data plane install.
//   -->
function splitMeta(raw) {
  const m = raw.match(/^\s*<!--\s*@snippet\s*([\s\S]*?)-->\s*\n?/);
  if (!m) return { meta: {}, body: raw.replace(/\s+$/, '') };
  const meta = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^\s*([A-Za-z][A-Za-z0-9_-]*)\s*:\s*(.*?)\s*$/);
    if (kv) meta[kv[1].toLowerCase()] = kv[2];
  }
  return { meta, body: raw.slice(m[0].length).replace(/\s+$/, '') };
}

// ── marker parsing ─────────────────────────────────────────────────────────

function parseAttrs(attrText, where) {
  const idMatch = attrText.match(/\bid\s*=\s*"([^"]+)"/);
  if (!idMatch) {
    throw new Error(`${where}: shared:begin marker has no id="..." attribute`);
  }
  const id = idMatch[1];

  let vars = {};
  const varsMatch = attrText.match(/\bvars\s*=\s*'([\s\S]*?)'/);
  if (!varsMatch && /\bvars\s*=/.test(attrText)) {
    // Catch vars="..." or bare vars={...}. Without this the attribute is
    // silently ignored and the author gets a confusing "needs vars not
    // supplied" for values they thought they had passed.
    throw new Error(
      `${where}: vars on id="${id}" must be single-quoted JSON, ` +
        `as vars='{"key":"value"}'`
    );
  }
  if (varsMatch) {
    try {
      vars = JSON.parse(varsMatch[1]);
    } catch (err) {
      throw new Error(
        `${where}: vars attribute on id="${id}" is not valid JSON (${err.message})`
      );
    }
    if (vars === null || typeof vars !== 'object' || Array.isArray(vars)) {
      throw new Error(`${where}: vars on id="${id}" must be a JSON object`);
    }
  }
  return { id, vars };
}

// ── rendering ──────────────────────────────────────────────────────────────

function render(snippet, vars, flavour, where) {
  const body = snippet[flavour];
  if (body === undefined) {
    throw new Error(
      `${where}: snippet "${snippet.id}" has no .${flavour} variant ` +
        `(expected docs/shared/snippets/${snippet.id}.${flavour})`
    );
  }

  const missing = new Set();
  const used = new Set();
  const out = body.replace(VAR_RE, (full, name) => {
    if (!Object.prototype.hasOwnProperty.call(vars, name)) {
      missing.add(name);
      return full;
    }
    used.add(name);
    return String(vars[name]);
  });

  if (missing.size) {
    throw new Error(
      `${where}: snippet "${snippet.id}" needs vars not supplied: ` +
        `${[...missing].sort().join(', ')}`
    );
  }
  const extra = Object.keys(vars).filter((k) => !used.has(k));
  return { out, extra };
}

// Re-apply the marker's own line prefix to every generated line. The prefix
// is leading whitespace, and in markdown it may also carry blockquote ">"
// markers: a snippet dropped inside a "> **Note:** ..." callout has to keep
// the quote running, or the callout splits in two at the generated block.
// A blank line inside a blockquote must still carry the ">".
function indentBlock(text, prefix) {
  if (!prefix) return text;
  const blankPrefix = prefix.includes('>') ? prefix.replace(/[ \t]+$/, '') : '';
  return text
    .split('\n')
    .map((line) => (line.trim() === '' ? blankPrefix : prefix + line))
    .join('\n');
}

// ── per-file processing ────────────────────────────────────────────────────

function processFile(file, snippets, warnings) {
  const rel = path.relative(REPO_ROOT, file);
  const flavour = path.extname(file) === '.md' ? 'md' : 'html';
  const original = fs.readFileSync(file, 'utf8');
  const lines = original.split('\n');

  const outLines = [];
  const usages = [];
  let i = 0;

  while (i < lines.length) {
    const begin = lines[i].match(BEGIN_OPEN_RE);
    if (!begin) {
      outLines.push(lines[i]);
      i += 1;
      continue;
    }

    const where = `${rel}:${i + 1}`;
    const indent = begin[1];

    // Consume the marker, which may span several lines, up to its closing -->.
    let markerEnd = i;
    while (markerEnd < lines.length && !lines[markerEnd].includes('-->')) {
      markerEnd += 1;
    }
    if (markerEnd === lines.length) {
      throw new Error(`${where}: shared:begin marker is never closed with -->`);
    }
    const markerLines = lines.slice(i, markerEnd + 1);
    // When the marker sits inside a markdown blockquote its continuation
    // lines carry the "> " too. Strip it before parsing, or the JSON breaks.
    const attrText = (
      indent.includes('>')
        ? [markerLines[0], ...markerLines.slice(1).map((l) => l.replace(/^(?:[ \t]*>)+[ \t]?/, ''))]
        : markerLines
    )
      .join('\n')
      .replace(/^[\s\S]*?shared:begin\b/, '')
      .replace(/-->[\s\S]*$/, '')
      .trim();
    // A var value can never contain "-->": the marker is itself an HTML
    // comment, so the first --> closes it and the rest of the JSON is lost.
    // Catch the truncation here rather than letting it surface as a JSON
    // parse error that points nowhere useful.
    if (!/'\s*$/.test(attrText) && /\bvars\s*=\s*'/.test(attrText)) {
      throw new Error(
        `${where}: the vars attribute looks truncated. A var value cannot ` +
          `contain "-->", because that closes the marker comment. Move the ` +
          `commented content into the snippet instead.`
      );
    }

    const { id, vars } = parseAttrs(attrText, where);

    // Find the matching end marker, rejecting a nested begin on the way.
    let j = markerEnd + 1;
    let end = -1;
    while (j < lines.length) {
      if (BEGIN_OPEN_RE.test(lines[j])) {
        throw new Error(
          `${where}: nested shared:begin at ${rel}:${j + 1} before shared:end`
        );
      }
      if (END_RE.test(lines[j])) {
        end = j;
        break;
      }
      j += 1;
    }
    if (end === -1) {
      throw new Error(`${where}: shared:begin id="${id}" has no shared:end`);
    }

    const snippet = snippets.get(id);
    if (!snippet) {
      throw new Error(
        `${where}: unknown snippet id "${id}". ` +
          `Add docs/shared/snippets/${id}.${flavour} or fix the id.`
      );
    }

    const { out, extra } = render(snippet, vars, flavour, where);
    if (extra.length) {
      warnings.push(
        `${where}: vars supplied but unused by snippet "${id}": ${extra.sort().join(', ')}`
      );
    }

    outLines.push(...markerLines);
    outLines.push(indent + '<!-- ' + GENERATED_NOTICE.replace('%s', `${id}.${flavour}`) + ' -->');
    outLines.push(indentBlock(out, indent));
    outLines.push(lines[end]);

    usages.push({ id, file: rel, line: i + 1 });
    i = end + 1;
  }

  const updated = outLines.join('\n');
  return { rel, changed: updated !== original, updated, usages };
}

// ── file discovery ─────────────────────────────────────────────────────────

function findTargets(dir) {
  let results = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      results = results.concat(findTargets(path.join(dir, entry.name)));
    } else if (entry.name.endsWith('.html') || entry.name.endsWith('.md')) {
      results.push(path.join(dir, entry.name));
    }
  }
  return results;
}

// ── main ───────────────────────────────────────────────────────────────────

function main(argv) {
  const flags = new Set(argv.filter((a) => a.startsWith('--')));
  const explicit = argv.filter((a) => !a.startsWith('--'));

  const check = flags.has('--check');
  const list = flags.has('--list');
  const verbose = flags.has('--verbose');

  const snippets = loadSnippets();

  if (list) {
    if (!snippets.size) {
      console.log('No snippets in docs/shared/snippets/.');
      return 0;
    }
    const allUsages = [];
    for (const f of findTargets(DOCS_ROOT)) {
      try {
        allUsages.push(...processFile(f, snippets, []).usages);
      } catch {
        // --list should survive a broken marker; the write/check runs report it.
      }
    }
    console.log(`${snippets.size} snippet(s) in docs/shared/snippets/\n`);
    for (const id of [...snippets.keys()].sort()) {
      const s = snippets.get(id);
      const flavours = ['html', 'md'].filter((f) => s[f] !== undefined).join(', ');
      const uses = allUsages.filter((u) => u.id === id);
      console.log(`  ${id}  [${flavours}]  used in ${uses.length} place(s)`);
      if (s.meta.title) console.log(`      ${s.meta.title}`);
      for (const u of uses) console.log(`      - ${u.file}:${u.line}`);
    }
    return 0;
  }

  let targets;
  if (explicit.length) {
    targets = explicit
      .map((p) => path.resolve(REPO_ROOT, p))
      .filter((p) => fs.existsSync(p) && /\.(html|md)$/.test(p));
  } else {
    targets = findTargets(DOCS_ROOT);
  }

  const warnings = [];
  const stale = [];
  const errors = [];
  let touched = 0;
  let withMarkers = 0;

  for (const file of targets) {
    let result;
    try {
      result = processFile(file, snippets, warnings);
    } catch (err) {
      errors.push(err.message);
      continue;
    }
    if (result.usages.length) withMarkers += 1;
    if (!result.changed) continue;

    if (check) {
      stale.push(result.rel);
    } else {
      fs.writeFileSync(file, result.updated, 'utf8');
      touched += 1;
      if (verbose) console.log(`updated  ${result.rel}`);
    }
  }

  for (const w of warnings) console.warn(`warning: ${w}`);
  for (const e of errors) console.error(`error: ${e}`);

  if (errors.length) {
    console.error(`\n${errors.length} error(s). Nothing was written.`);
    return 1;
  }

  if (check) {
    if (stale.length) {
      console.error('Shared content is out of date in:');
      for (const f of stale) console.error(`  ${f}`);
      console.error(
        '\nRun: node docs/shared/scripts/sync-shared-content.js\n' +
          'then stage the result.'
      );
      return 1;
    }
    console.log(`Shared content up to date (${withMarkers} file(s) with markers).`);
    return 0;
  }

  console.log(
    touched
      ? `Updated ${touched} file(s); ${withMarkers} file(s) use shared content.`
      : `Nothing to update; ${withMarkers} file(s) use shared content.`
  );
  return 0;
}

if (require.main === module) {
  process.exit(main(process.argv.slice(2)));
}

module.exports = { loadSnippets, processFile, findTargets };
