<#
.SYNOPSIS
    Installs the airs-gw Helm chart using the values.yaml downloaded from the
    SCM Gateway Registration wizard.

.DESCRIPTION
    Writes a small overlay values file holding the Service block and, when
    EnableJwtAuth is on, the JWT settings, then installs the chart with both
    files. Helm deep-merges value files left to right, so the registry
    credentials, PORTKEY_CLIENT_AUTH, and ORGANISATIONS_TO_SYNC from the
    wizard pass through untouched.

    LOG_STORE is deliberately left unset. See README.md.

.PARAMETER ParameterFile
    Path to Lab.parameters.psd1. Defaults to the copy beside this script.

.EXAMPLE
    ./03-Install-AigwDataPlane.ps1
#>

[CmdletBinding(SupportsShouldProcess)]
param(
    [string]$ParameterFile
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

Import-Module (Join-Path $PSScriptRoot 'LabCommon.psm1') -Force

$config = Get-LabConfig -Path $ParameterFile

Write-Host ''
Write-Host 'Phase 3: AI Gateway data plane' -ForegroundColor White

# ── Values file ──────────────────────────────────────────────────────────────
Write-LabStep 'Checking the SCM values file'

$valuesPath = Join-Path $PSScriptRoot $config.ScmValuesFile
if (-not (Test-Path $valuesPath)) {
    throw @"
Missing $valuesPath

Download it from Strata Cloud Manager:
  AI Gateway > Admin Settings > Gateway Registration >
  Configure Gateway Deployment > Download values.yaml

It carries a live registry password and Client Auth Key. Keep a backup in a
password manager and never commit it.
"@
}
Write-LabSuccess "Found $($config.ScmValuesFile)"

# ── Overlay ──────────────────────────────────────────────────────────────────
Write-LabStep 'Writing the overlay values file'

$overlayLines = @(
    '# Generated by 03-Install-AigwDataPlane.ps1. Edit Lab.parameters.psd1 instead.'
    'service:'
    '  type: LoadBalancer'
    '  port: 80'
    "  containerPort: $($config.GatewayPort)"
    'environment:'
    '  create: true'
    '  secret: true'
    '  data:'
    "    PORT: `"$($config.GatewayPort)`""
)

if ($config.EnableJwtAuth) {
    $overlayLines += '    JWT_ENABLED: "ON"'
    $overlayLines += "    JWT_LOCAL_AUTH_DEFAULT_SCOPES: `"$($config.JwtDefaultScopes)`""
    Write-LabInfo 'JWT validation enabled'
}

$overlayPath = Join-Path $PSScriptRoot '.values-overlay.yaml'
$overlayLines -join "`n" | Set-Content -Path $overlayPath -Encoding utf8
Write-LabSuccess "Wrote $overlayPath"

# ── Helm repo ────────────────────────────────────────────────────────────────
Write-LabStep 'Helm repository'

# This is the chart the SCM wizard generates a values.yaml for. It is not the
# same chart as portkey-ai/gateway: different registry, different value keys,
# different release name. Do not mix them.
Invoke-LabNative -FilePath 'helm' -ArgumentList @(
    'repo', 'add', 'airs-gw', $config.AirsGwRepoUrl, '--force-update'
)
Invoke-LabNative -FilePath 'helm' -ArgumentList @('repo', 'update', 'airs-gw')

# ── Install ──────────────────────────────────────────────────────────────────
Write-LabStep "Installing the chart into namespace $($config.AirsGwNamespace)"

if ($PSCmdlet.ShouldProcess('airs-gw', 'helm upgrade --install')) {
    $helmArgs = @(
        'upgrade', '--install', 'airs-gw', "airs-gw/$($config.AirsGwChart)"
        '--namespace', $config.AirsGwNamespace
        '--create-namespace'
        '-f', $valuesPath
        '-f', $overlayPath
        '--wait'
        '--timeout', '15m'
    )

    try {
        Invoke-LabNative -FilePath 'helm' -ArgumentList $helmArgs
    }
    catch {
        Write-LabWarning 'Helm reported a failure. Pod status:'
        & kubectl get pods -n $config.AirsGwNamespace
        throw
    }

    Write-LabSuccess 'Chart installed'
}

# ── Pods ─────────────────────────────────────────────────────────────────────
Write-LabStep 'Pod status'

& kubectl get pods -n $config.AirsGwNamespace

$notRunning = & kubectl get pods -n $config.AirsGwNamespace `
    -o 'jsonpath={range .items[?(@.status.phase!="Running")]}{.metadata.name}{"\t"}{.status.phase}{"\n"}{end}' 2>$null

if ($notRunning) {
    Write-LabWarning "Not every pod is Running:`n$notRunning"
    Write-LabWarning 'ImagePullBackOff points at the imageCredentials in values.yaml or egress to registry.portkey.ai.'
    Write-LabWarning "Logs: kubectl logs <POD> -n $($config.AirsGwNamespace) --tail=50"
}
else {
    Write-LabSuccess 'All pods Running'
}

# ── Load balancer address ────────────────────────────────────────────────────
Write-LabStep 'Waiting for the gateway load balancer'

$gatewayIp = Wait-LabLoadBalancerIp -ServiceName 'airs-gw' -Namespace $config.AirsGwNamespace
Set-LabState -Config $config -Name 'GatewayIp' -Value $gatewayIp

# ── Health check ─────────────────────────────────────────────────────────────
Write-LabStep 'Health check'

try {
    $health = Invoke-RestMethod -Uri "http://$gatewayIp/v1/health" -TimeoutSec 30
    Write-LabSuccess "Gateway healthy: $($health | ConvertTo-Json -Compress)"
}
catch {
    Write-LabWarning "Health check did not succeed yet: $($_.Exception.Message)"
    Write-LabWarning 'Load balancer programming can lag the address assignment by a minute. Retry with:'
    Write-LabWarning "  Invoke-RestMethod http://$gatewayIp/v1/health"
}

Write-Host ''
Write-Host 'Phase 3 complete.' -ForegroundColor Green
Write-Host ''
Write-Host 'Register these in SCM under Organization Details > General:' -ForegroundColor Yellow
Write-Host "  Gateway URLs:      http://$gatewayIp/v1"
Write-Host "  MCP Gateway URLs:  http://${gatewayIp}:8788"
Write-Host ''
Write-LabInfo 'Next: ./04-New-TrafficGeneratorVm.ps1'
